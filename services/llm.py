def ask_ai(question: str, context: str = "", backend: str = "auto", key_overrides: Optional[Dict[str, str]] = None) -> str:
    """
    Call the best available language model.

    Routing (files / YouTube / primary search / greetings) belongs in routes/chat.py.
    This function only:
      1. Rejects empty input
      2. Optionally enriches empty context with a last-resort search for live facts
      3. Failovers across providers
    """
    if not question or len(question.strip()) < 1:
        return "Please provide a valid question."

    q = question.strip()
    # Colab local LLM only when user selected colab / local — not on every auto chat (latency)
    if (backend or "auto").lower() in ("colab", "local", "ollama", "lmstudio"):
        local_ans = try_colab_local_llm(q, context or "")
        if local_ans:
            return local_ans
    if context and VISION_SYSTEM_CORE not in (context or ""):
        context = VISION_SYSTEM_CORE + "\n\n" + (context or "")
    elif not context:
        context = VISION_SYSTEM_CORE
    logger.info("=" * 50)
    logger.info(f"AI Request: {q[:80]}...")
    logger.info(f"Backend: {backend} | Context chars: {len(context or '')}")
    logger.info("=" * 50)

    # Narrow ambiguity guard — only pure pronouns / "help"
    if is_ambiguous(q) and not (context or "").strip():
        logger.info("Ambiguous prompt with empty context — asking for clarification")
        return "Could you please clarify what you mean? I want to give you the most accurate answer."

    # Last-resort search ONLY when chat did not already inject results
    # and the question clearly needs current data.
    if is_uncertain(q) and not _context_already_has_search(context or ""):
        try:
            from services.search import search_web

            logger.info(f"Last-resort web search for: {q[:60]}")
            search_results = search_web(q, max_results=5, use_cache=True)
            if search_results and not search_results.startswith("[No search"):
                context = (context or "") + f"\n\n[WEB SEARCH RESULTS]\n{search_results}"
        except Exception as e:
            logger.warning(f"Last-resort search failed: {e}")

    # Simple greetings — instant local reply (no provider latency)
    _ql = q.lower().strip().rstrip("!.")
    _greetings = {
        "hi", "hello", "hey", "hiya", "yo", "salam", "assalamualaikum",
        "assalam o alaikum", "asalamualaikum", "hi dear", "hello dear",
        "hey there", "good morning", "good evening", "good afternoon",
    }
    if _ql in _greetings or (_ql.startswith("hi ") and len(_ql) < 20):
        return "Hi there! How can I help you today?"

    # Colab worker ONLY when proven live (fast health cache). Dead ngrok must not delay chat.
    try:
        from services.colab_worker import is_live as _colab_live, chat as _colab_chat
        if backend == "colab" or (backend == "auto" and _colab_live()):
            colab_ans = _colab_chat(q, context or "", model=backend)
            if colab_ans:
                logger.info("✅ Success: Colab worker")
                return colab_ans
    except Exception as e:
        logger.warning(f"Colab worker skip: {e}")

    def _is_safety_refusal(text: str) -> bool:
        """Detect model safety blocks that refuse educational exam help."""
        if not text:
            return True
        t = text.lower()
        markers = (
            "user safety",
            "safety categories",
            "unauthorized advice",
            "i can't help with that",
            "i cannot help with that",
            "against my guidelines",
            "violates my guidelines",
            "cannot assist with exam",
            "won't solve homework",
            "will not solve homework",
            "academic integrity policy",
        )
        # Short refusal-only payloads
        if any(m in t for m in markers) and len(text) < 600:
            return True
        if t.strip().startswith("user safety"):
            return True
        return False

    keys = _resolve_runtime_keys(key_overrides)
    # Prefer explicit local backends early when selected
    if (backend or "").lower() in ("ollama", "lmstudio", "lm-studio", "local", "openai-compat", "custom", "openai"):
        pass  # chain already specialized
    providers = _build_provider_chain(backend, keys)
    # Large exam PDFs: prefer Gemini Flash (1M context) before short-window free models
    if _is_document_context(context or "") and (backend or "auto").lower() in ("auto", "default", "light", "fast"):
        gemini_first = [p for p in providers if "gemini" in p[0]]
        others = [p for p in providers if "gemini" not in p[0]]
        if gemini_first:
            providers = gemini_first + others
            logger.info("Document/exam context → Gemini prioritized for long PDF")
    # Soft fallback: if user picked one free provider and it dies, still try other free keys
    bsel = (backend or "auto").lower().strip()
    if bsel in ("groq", "openrouter", "deepseek", "gemini") and not _is_document_context(context or ""):
        fallback = _build_provider_chain("auto", keys)
        seen = {p[0] for p in providers}
        for item in fallback:
            if item[0] not in seen:
                providers.append(item)
                seen.add(item[0])
    errors: List[str] = []

    for provider_name, provider_func in providers:
        try:
            result = provider_func(q, context or "")
            if result and _is_safety_refusal(result):
                logger.warning(f"⚠️ {provider_name} safety-refusal — trying next provider")
                errors.append(f"{provider_name}: safety refusal")
                continue
            if result and len(result) > 10 and not result.startswith("[Error"):
                logger.info(f"✅ Success: {provider_name} ({len(result)} chars)")
                if is_vague(result) and not _context_already_has_search(context or ""):
                    try:
                        from services.search import search_web

                        extra = search_web(q, max_results=5, use_cache=True)
                        if extra and not extra.startswith("[No search"):
                            refined = provider_func(
                                q,
                                (context or "") + f"\n\n[WEB SEARCH RESULTS]\n{extra}",
                            )
                            if (
                                refined
                                and len(refined) > 10
                                and not is_vague(refined)
                                and not _is_safety_refusal(refined)
                            ):
                                return refined
                    except Exception as e:
                        logger.debug(f"Vague-response refine failed: {e}")
                return result
            errors.append(f"{provider_name}: empty/invalid response")
        except Exception as e:
            errors.append(f"{provider_name}: {str(e)[:80]}")
            logger.warning(f"Provider {provider_name} raised: {e}")
            continue

    error_summary = "All AI models unavailable."
    if errors:
        error_summary += f" Last errors: {', '.join(errors[:3])}"
    logger.error(error_summary)
    return (
        "I couldn't get a reply from the free model cascade just now "
        "(rate limit, empty response, or temporary outage).\n\n"
        "**Try:** select **Groq** or **OpenRouter** in the model menu, wait a few seconds, "
        "or rephrase the question.\n\n"
        f"Details: {error_summary}"
    )


