def _prefer_question_body(context: str, char_limit: int) -> str:
    """
    Keep exam questions, not only the cover sheet.
    Prefer pages that look like Q1/Q2... over pure front-matter.
    """
    if len(context) <= char_limit:
        return context
    # Split by page markers when present
    parts = re.split(r"(?=--- Page \d+ ---)", context)
    if len(parts) <= 1:
        # No page markers: keep head (guidance) + tail (often answers/last qs)
        head = context[: char_limit // 3]
        body = context[char_limit // 3 :]
        # Drop obvious front-matter lines from middle if needed
        return (head + "\n\n[...middle pages prioritized...]\n\n" + body[-(char_limit - len(head) - 40):])[:char_limit]

    scored = []
    for p in parts:
        score = 0
        low = p.lower()
        if re.search(r"\b(q\s*\d+|question\s*\d+|\d+\s*\([a-z]\))", low):
            score += 5
        if "mark" in low or "total for question" in low:
            score += 2
        if "formulae" in low or "equation sheet" in low or "constant" in low:
            score -= 3
        if "candidate surname" in low or "centre number" in low:
            score -= 4
        scored.append((score, p))
    # Sort high-score pages first but preserve original order among equals via stable sort
    ranked = sorted(enumerate(scored), key=lambda x: (-x[1][0], x[0]))
    chosen = []
    total = 0
    # Always include first chunk (tag + guidance + page 1 header)
    if parts:
        chosen.append(parts[0])
        total = len(parts[0])
    for _, (score, p) in ranked:
        if p is parts[0]:
            continue
        if total + len(p) > char_limit:
            remain = char_limit - total - 20
            if remain > 500:
                chosen.append(p[:remain] + "\n...[page truncated]")
                total = char_limit
            break
        chosen.append(p)
        total += len(p)
    out = "\n".join(chosen)
    if len(out) > char_limit:
        out = out[:char_limit] + "\n...[truncated]"
    return out


def truncate_context(context: str, model_id: str, max_tokens: int = 4000) -> str:
    """Truncate context with document-aware limits so exam papers are not reduced to the cover page."""
    if not context:
        return ""
    token_limit = 4096
    if model_id in GEMINI_MODELS:
        token_limit = int(GEMINI_MODELS[model_id]["tokens"])
    doc = _is_document_context(context)
    # Documents need far more than 4k tokens of context
    if doc:
        if model_id in GEMINI_MODELS:
            char_limit = min(token_limit * 3, 200_000)
        else:
            # Groq / OpenRouter / DeepSeek — use large window when model supports it
            char_limit = max(max_tokens * 4, 48_000)
            char_limit = min(char_limit, 100_000)
    else:
        char_limit = min(token_limit * 4, max_tokens * 4 if model_id not in GEMINI_MODELS else token_limit * 4)
        char_limit = min(char_limit, 120_000 if model_id in GEMINI_MODELS else max_tokens * 4)

    if len(context) <= char_limit:
        return context
    if doc:
        return _prefer_question_body(context, char_limit)
    return context[:char_limit] + "\n...[truncated]"

