def _build_provider_chain(backend: str, keys: Optional[Dict[str, str]] = None) -> List[tuple]:
    """Build ordered provider callables. Per-request keys — never mutate module globals."""
    keys = keys or {}
    from services.security import validate_openai_compat_base

    g_key = keys.get("GOOGLE_API_KEY")
    groq_key = keys.get("GROQ_API_KEY")
    ds_key = keys.get("DEEPSEEK_API_KEY")
    or_key = keys.get("OPENROUTER_API_KEY")
    compat_base = validate_openai_compat_base(keys.get("OPENAI_COMPAT_BASE") or "") or (
        OPENAI_COMPAT_BASE if not keys.get("OPENAI_COMPAT_BASE") else None
    )
    compat_key = keys.get("OPENAI_COMPAT_KEY") or OPENAI_COMPAT_KEY
    compat_model = keys.get("OPENAI_COMPAT_MODEL") or OPENAI_COMPAT_MODEL

    g25_flash = ("gemini-2.5-flash", lambda q, c: ask_gemini(q, c, "gemini-2.5-flash"))
    g25_pro = ("gemini-2.5-pro", lambda q, c: ask_gemini(q, c, "gemini-2.5-pro"))
    g20_flash = ("gemini-2.0-flash", lambda q, c: ask_gemini(q, c, "gemini-2.0-flash"))
    g15_flash = ("gemini-1.5-flash", lambda q, c: ask_gemini(q, c, "gemini-1.5-flash"))
    g15_pro = ("gemini-1.5-pro", lambda q, c: ask_gemini(q, c, "gemini-1.5-pro"))
    deepseek = ("deepseek", lambda q, c: ask_deepseek(q, c, api_key=ds_key))
    groq = ("groq", lambda q, c: ask_groq(q, c, api_key=groq_key))
    openrouter = ("openrouter", lambda q, c: ask_openrouter(q, c, api_key=or_key))
    ollama = ("ollama", lambda q, c: ask_ollama(q, c))
    lmstudio = ("lmstudio", lambda q, c: ask_lmstudio(q, c))
    custom = ("openai-compat", lambda q, c: ask_openai_compat(
        q, c,
        base_url=compat_base or "",
        api_key=compat_key or "",
        model=compat_model or "local-model",
        provider_label="OpenAI-compat",
    )) if compat_base else ("openai-compat", lambda q, c: None)

    b = (backend or "auto").lower().strip()
    # Routing profiles → map to provider backend
    try:
        from services.routing_profiles import resolve_chain, PROFILES
        if b in PROFILES and b not in ("auto", "gemini", "deepseek", "groq", "openrouter"):
            chain_ids = resolve_chain(b)
            ordered = []
            mapping = {
                "groq": groq, "openrouter": openrouter, "deepseek": deepseek,
                "gemini": g25_flash, "auto": None,
            }
            for cid in chain_ids:
                if cid == "auto":
                    break
                item = mapping.get(cid)
                if item and item not in ordered:
                    ordered.append(item)
            if ordered:
                return ordered + [x for x in [groq, openrouter, deepseek, g25_flash] if x not in ordered]
    except Exception:
        pass
    if b in ("ollama", "local-ollama"):
        return [ollama, custom]
    if b in ("lmstudio", "lm-studio", "local-lmstudio"):
        return [lmstudio, custom]
    if b in ("local", "openai-compat", "custom", "openai"):
        return [custom, ollama, lmstudio]
    if b == "auto":
        # Light & free first for low latency chat (user request: chat only light models)
        chain = [groq, openrouter, deepseek, g25_flash]
        # Gemini Pro only if explicitly needed — skipped on auto to keep chat fast
        if LOCAL_LLM_ENABLED and (OPENAI_COMPAT_BASE or keys.get("OPENAI_COMPAT_BASE")):
            chain = [custom] + chain
        return chain
    if b in ("light", "fast", "free"):
        return [groq, openrouter, deepseek, g25_flash]
    if b == "gemini":
        return [g25_flash, g25_pro]
    if b == "deepseek":
        return [deepseek]
    if b == "groq":
        return [groq]
    if b == "openrouter":
        return [openrouter]
    return [groq, g25_flash, openrouter, deepseek, g20_flash, custom]


