def is_complex_reasoning(question: str) -> bool:
    """Heuristic: math / multi-step / deep analysis → prefer stronger / local path."""
    q = (question or "").lower()
    if len(q) < 20:
        return False
    keys = (
        "step by step", "step-by-step", "prove that", "derive", "calculate",
        "solve for", "integral", "derivative", "equation", "theorem",
        "algorithm complexity", "write a proof", "rigorous", "formal proof",
        "optimize this code", "debug this entire", "refactor architecture",
        "compare and contrast in detail", "why does", "how does quantum",
    )
    if any(k in q for k in keys):
        return True
    # dense math symbols
    if sum(1 for c in question if c in "∫∑√≈≤≥≠∂∇") >= 2:
        return True
    if re.search(r"\b\d+\s*[\+\-\*/^=]\s*\d+", q) and "solve" in q:
        return True
    return False


def try_colab_local_llm(question: str, context: str = "") -> Optional[str]:
    """
    Optional Colab GPU LLM for complex prompts.
    Only used when worker is live and LOCAL_LLM is enabled on worker.
    Does not replace Groq for normal chat.
    """
    if not is_complex_reasoning(question):
        return None
    if (os.getenv("USE_COLAB_LOCAL_LLM", "1") or "1").strip().lower() in ("0", "false", "no"):
        return None
    try:
        from services.colab_worker import chat as worker_chat, is_enabled
        if not is_enabled():
            return None
        # Hint worker to use local model if available
        ans = worker_chat(question, context or "", model="local")
        if ans and len(ans.strip()) > 20:
            logger.info("Answered via Colab local LLM path")
            return ans.strip()
    except Exception as e:
        logger.debug(f"Colab local LLM skip: {e}")
    return None



