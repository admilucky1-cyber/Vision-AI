def stream_openai_compatible(
    question: str,
    context: str = "",
    provider: str = "auto",
):
    """
    Yield text deltas from Groq / OpenRouter / DeepSeek (OpenAI-compatible SSE).
    Falls back to empty generator if streaming unavailable — caller should use ask_*.
    """
    import json as _json

    system_prompt = assemble_dynamic_prompt(question, context)
    candidates = []

    if provider in ("auto", "groq", "light") and GROQ_AVAILABLE:
        models = GROQ_MODELS if "GROQ_MODELS" in globals() else [
            {"id": "openai/gpt-oss-20b"},
            {"id": "openai/gpt-oss-120b"},
        ]
        for m in models[:2]:
            candidates.append(
                (
                    "groq",
                    m["id"],
                    "https://api.groq.com/openai/v1/chat/completions",
                    {"Authorization": f"Bearer {GROQ_API_KEY}", "Content-Type": "application/json"},
                    24_000 if _is_document_context(context) else 8000,
                )
            )
    if provider in ("auto", "openrouter") and OPENROUTER_AVAILABLE:
        for m in (OPENROUTER_MODELS or [])[:2]:
            candidates.append(
                (
                    "openrouter",
                    m["id"],
                    "https://openrouter.ai/api/v1/chat/completions",
                    {
                        "Authorization": f"Bearer {OPENROUTER_KEY}",
                        "Content-Type": "application/json",
                        "HTTP-Referer": "https://vision-ai.app",
                        "X-Title": "Vision AI",
                    },
                    24_000 if _is_document_context(context) else 8000,
                )
            )
    if provider in ("auto", "deepseek") and DEEPSEEK_AVAILABLE:
        candidates.append(
            (
                "deepseek",
                "deepseek-chat",
                "https://api.deepseek.com/v1/chat/completions",
                {"Authorization": f"Bearer {DEEPSEEK_API_KEY}", "Content-Type": "application/json"},
                24_000 if _is_document_context(context) else 8000,
            )
        )

    for name, model_id, url, headers, trunc in candidates:
        try:
            truncated = truncate_context(context, name, trunc)
            payload = {
                "model": model_id,
                "messages": [
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": f"Context:\n{truncated}\n\nQuestion:\n{question}"},
                ],
                "temperature": 0.6,
                "max_tokens": _out_tokens(context, 4096),
                "stream": True,
            }
            with requests.post(url, headers=headers, json=payload, timeout=_provider_timeout(context, 60), stream=True) as resp:
                if resp.status_code != 200:
                    logger.debug(f"stream {name}/{model_id} HTTP {resp.status_code}")
                    continue
                yield {"event": "meta", "provider": name, "model": model_id}
                for line in resp.iter_lines(decode_unicode=True):
                    if not line:
                        continue
                    if line.startswith("data: "):
                        data = line[6:].strip()
                        if data == "[DONE]":
                            break
                        try:
                            chunk = _json.loads(data)
                            delta = ((chunk.get("choices") or [{}])[0].get("delta") or {}).get("content") or ""
                            if delta:
                                yield {"event": "token", "text": delta}
                        except Exception:
                            continue
                yield {"event": "done", "provider": name, "model": model_id}
                return
        except Exception as e:
            logger.debug(f"stream {name} failed: {e}")
            continue

